import { describe, expect, it } from 'vitest';
import { resolveDescription } from './articles';

const content =
  "import { ArticleLayout } from '../../components/ArticleLayout';\n\nexport const meta = {\n  path: \"/blog/x\",\n  date: \"2020/10/25\",\n};\n\nexport default ({ children }) => <ArticleLayout meta={meta}>{children}</ArticleLayout>;\n\n# はじめに\n本文A";

// 注: extractIntroSection の終端 `\z` が JS では機能しないため、見出しのみの記事では
// 「はじめに」見出し行が残った自動生成文になる（計画で本チケット対象外と合意済み）。
const autoGenerated = 'はじめに\n本文A…';

describe('articles.ts', () => {
  describe('resolveDescription', () => {
    it('should adopt the frontmatter description as is', () => {
      // Given
      const description = 'Vue3を試す記事';
      const body = '# はじめに\n本文A';
      // When
      const result = resolveDescription(description, body);
      // Then
      expect(result).toBe('Vue3を試す記事');
    });

    it('should not leak a multi-line export const meta into the auto-generated description', () => {
      // Given
      const description = undefined;
      // When
      const result = resolveDescription(description, content);
      // Then
      expect(result).toBe(autoGenerated);
      expect(result).not.toContain('path:');
    });

    it('should fall back to auto generation when description is empty', () => {
      // Given / When
      const result = resolveDescription('', content);
      // Then
      expect(result).toBe(autoGenerated);
    });

    it('should fall back to auto generation when description is whitespace only', () => {
      // Given / When
      const result = resolveDescription('   ', content);
      // Then
      expect(result).toBe(autoGenerated);
    });
  });
});
